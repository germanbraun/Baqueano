"""queries/*.rq: starter SPARQL queries built from the discovery.

One function per query kind, plain text templates. Every query starts with a
comment saying what it does and where its data came from, declares its
PREFIXes and ends with LIMIT. With --graph, the patterns go inside GRAPH <iri>.

render(discovery) -> {file name: query text}
"""

from __future__ import annotations

from baqueano.generate import thresholds as th
from baqueano.generate.names import slug, unique, unique_map, variable
from baqueano.generate.prefixes import PrefixWriter
from baqueano.model import ClassInfo, ClassProfile, Discovery, Link
from baqueano.profiling import RDF_TYPE


# -- small text helpers --------------------------------------------------------

def comment(*lines: str) -> str:
    return "".join(f"# {line}\n" for line in lines)


def where(lines: list[str], graph: str | None) -> str:
    """WHERE block with one pattern per line, inside GRAPH <graph> when scoped."""
    if graph is None:
        body = "".join(f"  {line}\n" for line in lines)
    else:
        body = f"  GRAPH <{graph}> {{\n" + "".join(f"    {line}\n" for line in lines) + "  }\n"
    return "WHERE {\n" + body + "}\n"


def query(header: str, pw: PrefixWriter, select: str, where_block: str, tail: str = "") -> str:
    """Assemble header, PREFIXes (only those used), SELECT, WHERE and LIMIT."""
    prefixes = pw.declarations()
    return (header + (prefixes and "\n" + prefixes) + "\n" + select + "\n" + where_block
            + tail + f"LIMIT {th.QUERY_LIMIT}\n")


def aligned(lines: list[tuple[str, str]]) -> list[str]:
    """Pattern lines with their trailing comments aligned."""
    width = max(len(code) for code, _ in lines) if lines else 0
    return [f"{code.ljust(width)} # {note}" if note else code for code, note in lines]


def is_a(pw: PrefixWriter, discovery: Discovery) -> str:
    """The predicate linking instances to classes: 'a', or the --class-property, written short."""
    return "a" if discovery.class_property == RDF_TYPE else pw.iri(discovery.class_property)


# -- facts about the discovery ------------------------------------------------

def class_info(discovery: Discovery, class_iri: str) -> ClassInfo | None:
    return next((c for c in discovery.classes if c.iri == class_iri), None)


def count_text(discovery: Discovery, class_iri: str) -> str:
    info = class_info(discovery, class_iri)
    if info is None or info.count is None:
        return "instance count unknown"
    how = "exact count" if info.count_exact else "count declared in VoID"
    return f"{info.count} instances ({how})"


def label_property(discovery: Discovery, class_iri: str) -> str | None:
    """Best label property for a class: one seen in its profile, else the most
    preferred one seen anywhere (a guess, used in OPTIONAL so it is harmless)."""
    prof = next((p for p in discovery.profiles if p.class_iri == class_iri), None)
    if prof is not None:
        paths = {pp.path for pp in prof.properties}
        return next((lp for lp in discovery.label_properties if lp in paths), None)
    return discovery.label_properties[0] if discovery.label_properties else None


# -- one function per query kind ----------------------------------------------

def overview(discovery: Discovery) -> str:
    pw = PrefixWriter()
    graph = discovery.graph_scope
    if discovery.graphs and graph is None:
        header = comment("Classes and their number of instances, per named graph.",
                         f"Generated by Baqueano from {discovery.endpoint}: "
                         f"{len(discovery.graphs)} named graph(s) were found.")
        return query(header, pw, "SELECT ?g ?class (COUNT(?s) AS ?n)",
                     where([f"GRAPH ?g {{ ?s {is_a(pw, discovery)} ?class }}"], None),
                     "GROUP BY ?g ?class\nORDER BY DESC(?n)\n")
    scope_note = f" in graph <{graph}>" if graph else ""
    header = comment(f"Classes and their number of instances{scope_note}.",
                     f"Generated by Baqueano from {discovery.endpoint}: {len(discovery.classes)} classes were found.")
    return query(header, pw, "SELECT ?class (COUNT(?s) AS ?n)", where([f"?s {is_a(pw, discovery)} ?class ."], graph),
                 "GROUP BY ?class\nORDER BY DESC(?n)\n")


def class_list(discovery: Discovery, prof: ClassProfile) -> str:
    pw = PrefixWriter()
    cls = pw.iri(prof.class_iri)
    var, label_var = unique([variable(prof.class_iri), "label"], separator="")
    lines = [f"?{var} {is_a(pw, discovery)} {cls} ."]
    lp = label_property(discovery, prof.class_iri)
    if lp:
        lines.append(f"OPTIONAL {{ ?{var} {pw.iri(lp)} ?{label_var} }}")
        label_note = f"Label property: {pw.iri(lp)} (seen in the sample)."
        select = f"SELECT ?{var} ?{label_var}"
    else:
        label_note = "No label property was detected for this class."
        select = f"SELECT ?{var}"
    header = comment(f"Instances of {cls}" + (", with their label." if lp else "."),
                     f"Generated by Baqueano: {cls} has {count_text(discovery, prof.class_iri)}.",
                     label_note)
    return query(header, pw, select, where(lines, discovery.graph_scope))


def class_example(discovery: Discovery, prof: ClassProfile) -> str:
    pw = PrefixWriter()
    cls = pw.iri(prof.class_iri)
    header = comment(f"All properties of one real instance of {cls}.",
                     f"Generated by Baqueano: <{prof.example_instance}> is the instance with the most",
                     f"properties in a sample of {prof.sample_size} ({prof.sample_method}).")
    return query(header, pw, "SELECT ?property ?value",
                 where([f"<{prof.example_instance}> ?property ?value ."], discovery.graph_scope),
                 "ORDER BY ?property\n")


def class_table(discovery: Discovery, prof: ClassProfile) -> str:
    pw = PrefixWriter()
    cls = pw.iri(prof.class_iri)
    columns = [pp for pp in prof.properties
               if pp.path != discovery.class_property
               and pp.support >= th.PROPERTY_MIN_SUPPORT][:th.TABLE_MAX_COLUMNS]
    names = unique([variable(prof.class_iri)] + [variable(pp.path) for pp in columns], separator="")
    var, column_vars = names[0], names[1:]
    lines = [(f"?{var} {is_a(pw, discovery)} {cls} .", "")]
    for pp, cv in zip(columns, column_vars):
        lines.append((f"OPTIONAL {{ ?{var} {pw.iri(pp.path)} ?{cv} }}", f"support {pp.support:.2f}"))
    header = comment(f"Instances of {cls} with their most frequent properties.",
                     f"Generated by Baqueano from a sample of {prof.sample_size} instances of {cls}"
                     f" ({prof.sample_method}).")
    select = "SELECT " + " ".join(f"?{v}" for v in names)
    return query(header, pw, select, where(aligned(lines), discovery.graph_scope))


def link_join(discovery: Discovery, link: Link) -> str:
    pw = PrefixWriter()
    source, target, prop = pw.iri(link.source_class), pw.iri(link.target_class), pw.iri(link.path)
    s, t = unique([variable(link.source_class), variable(link.target_class)], separator="")
    isa = is_a(pw, discovery)
    lines = [f"?{s} {isa} {source} .", f"?{s} {prop} ?{t} .", f"?{t} {isa} {target} ."]
    select_vars = []
    for v, cls in ((s, link.source_class), (t, link.target_class)):
        select_vars.append(v)
        lp = label_property(discovery, cls)
        if lp:
            lines.append(f"OPTIONAL {{ ?{v} {pw.iri(lp)} ?{v}Label }}")
            select_vars.append(f"{v}Label")
    header = comment(f"{source} linked to {target} through {prop}, with labels on both sides.",
                     f"Generated by Baqueano: about {link.support:.0%} of the sampled {source} instances "
                     f"have such a link.")
    return query(header, pw, "SELECT " + " ".join(f"?{v}" for v in select_vars),
                 where(lines, discovery.graph_scope))


# -- all files -----------------------------------------------------------------

def link_file_names(links: list[Link], slugs: dict[str, str]) -> list[str]:
    """20-<A>-to-<B>.rq; when A and B are joined by several properties, the
    property goes in the name too: 20-<A>-<property>-<B>.rq."""
    pairs = [(link.source_class, link.target_class) for link in links]
    names = []
    for link, pair in zip(links, pairs):
        a, b = slugs[link.source_class], slugs[link.target_class]
        names.append(f"20-{a}-{slug(link.path)}-{b}" if pairs.count(pair) > 1 else f"20-{a}-to-{b}")
    return [f"{n}.rq" for n in unique(names)]


def render(discovery: Discovery) -> dict[str, str]:
    links = [link for link in discovery.links if link.support >= th.LINK_MIN_SUPPORT][:th.MAX_LINK_QUERIES]
    class_iris = [p.class_iri for p in discovery.profiles]
    class_iris += [c for link in links for c in (link.source_class, link.target_class)]
    slugs = unique_map(class_iris, slug)

    files = {"00-overview.rq": overview(discovery)}
    for prof in discovery.profiles:
        name = slugs[prof.class_iri]
        files[f"10-{name}-list.rq"] = class_list(discovery, prof)
        if prof.example_instance:
            files[f"11-{name}-example.rq"] = class_example(discovery, prof)
        files[f"12-{name}-table.rq"] = class_table(discovery, prof)
    for file_name, link in zip(link_file_names(links, slugs), links):
        files[file_name] = link_join(discovery, link)
    return files
