import json

import pytest
from rdflib.plugins.sparql import prepareQuery

from baqueano.generate import queries, thresholds as th
from baqueano.model import ClassProfile, Discovery, Link, discovery_from_dict, discovery_to_dict
from tests.sample_discovery import PERSON, PLACE, S, sample_discovery

GRAPH = "http://ex/graph/people"


@pytest.fixture(scope="module")
def files():
    return queries.render(sample_discovery())


def test_file_names(files):
    assert sorted(files) == [
        "00-overview.rq",
        "10-person-list.rq", "10-place-list.rq",
        "11-person-example.rq", "11-place-example.rq",
        "12-person-table.rq", "12-place-table.rq",
        "20-person-to-person.rq", "20-person-to-place.rq", "20-place-to-place.rq",
    ]


@pytest.mark.parametrize("graph", [None, GRAPH])
def test_every_query_parses_and_is_well_formed(graph):
    for name, text in queries.render(sample_discovery(graph_scope=graph)).items():
        prepareQuery(text)                       # fails if a PREFIX is missing
        assert text.startswith("# "), name
        assert text.rstrip().endswith(f"LIMIT {th.QUERY_LIMIT}"), name
        assert "SERVICE" not in text
        if graph and name != "00-overview.rq":
            assert f"GRAPH <{graph}>" in text, name


def test_table_query(files):
    text = files["12-person-table.rq"]
    assert text.splitlines()[1] == \
        "# Generated by Baqueano from a sample of 200 instances of schema:Person (first-n)."
    assert "SELECT ?person ?name ?birthDate ?birthPlace ?knows ?nick ?email ?homepage" in text
    assert "faxNumber" not in text                   # below PROPERTY_MIN_SUPPORT
    assert "OPTIONAL { ?person schema:name ?name }" in text
    support_comments = [line for line in text.splitlines() if "# support" in line]
    assert support_comments[0].endswith("# support 1.00")
    assert len({line.index("#") for line in support_comments}) == 1   # aligned
    assert "PREFIX schema: <https://schema.org/>" in text
    assert "PREFIX rdfs:" not in text                # only declared when used


def test_table_column_cap():
    d = sample_discovery()
    from baqueano.model import PropertyProfile
    d.profiles[0].properties = [PropertyProfile(f"{S}p{i}", 0.9, 1, 0, 1) for i in range(12)]
    text = queries.render(d)["12-person-table.rq"]
    assert text.count("OPTIONAL") == th.TABLE_MAX_COLUMNS


def test_list_query_uses_label_property(files):
    person = files["10-person-list.rq"]
    assert "OPTIONAL { ?person schema:name ?label }" in person
    assert "200 instances (exact count)" in person
    place = files["10-place-list.rq"]
    assert "OPTIONAL { ?place rdfs:label ?label }" in place
    assert "50 instances (count declared in VoID)" in place


def test_example_query(files):
    assert "<http://ex/person/1> ?property ?value ." in files["11-person-example.rq"]


def test_self_link_gets_distinct_variables(files):
    text = files["20-person-to-person.rq"]
    assert "?person schema:knows ?person2 ." in text
    assert "SELECT ?person ?personLabel ?person2 ?person2Label" in text


def test_link_query_with_labels_on_both_sides(files):
    text = files["20-person-to-place.rq"]
    assert "OPTIONAL { ?person schema:name ?personLabel }" in text
    assert "OPTIONAL { ?place rdfs:label ?placeLabel }" in text
    assert "about 97%" in text


def test_several_properties_between_same_classes():
    d = sample_discovery()
    d.links.append(Link(PERSON, S + "deathPlace", PLACE, 0.4))
    names = sorted(n for n in queries.render(d) if n.startswith("20-person"))
    assert names == ["20-person-birth-place-place.rq", "20-person-death-place-place.rq",
                     "20-person-to-person.rq"]


def test_weak_links_get_no_query():
    d = sample_discovery()
    d.links = [Link(PERSON, S + "knows", PERSON, th.LINK_MIN_SUPPORT - 0.01)]
    assert not [n for n in queries.render(d) if n.startswith("20-")]


def test_overview_per_graph_or_scoped():
    assert "GRAPH ?g { ?s a ?class }" in queries.render(sample_discovery())["00-overview.rq"]
    scoped = queries.render(sample_discovery(graph_scope=GRAPH))["00-overview.rq"]
    assert f"GRAPH <{GRAPH}>" in scoped and "?g" not in scoped


def test_unknown_namespace_written_in_full():
    d = Discovery(endpoint="http://e", started_at="t",
                  profiles=[ClassProfile("http://unknown.org/v/Thing", 1, "first-n", False, None)])
    text = queries.render(d)["12-thing-table.rq"]
    assert "?thing a <http://unknown.org/v/Thing> ." in text
    assert "PREFIX" not in text
    prepareQuery(text)


def test_empty_discovery_still_has_overview():
    files = queries.render(Discovery(endpoint="http://e", started_at="t"))
    assert list(files) == ["00-overview.rq"]
    prepareQuery(files["00-overview.rq"])


def test_reads_only_what_discovery_json_holds():
    d = sample_discovery()
    reloaded = discovery_from_dict(json.loads(json.dumps(discovery_to_dict(d))))
    assert queries.render(reloaded) == queries.render(d)
